REWRITES["py.random.shuffle"] = """
**一句话：** 从最后一个位置开始，每个位置和前面某个随机位置交换一下，交换完整串就乱了。

**执行逻辑：**

1. 从最后一个位置 i 开始
2. 在 0..i 里摇一个随机位置 j
3. 交换 i 和 j 两个位置上的元素
4. i 往前挪一位，重复 2–3
5. 走到第 1 个位置就结束——**原地改，不返回新列表**

**机器层（可跳过）：** 线性时间；每一步只做一次交换。

**边界（从逻辑推出来）：**

- 第 3 步是「和已经处理过的区间以外的位置」交换，所以每种排列出现概率相同；用 `sorted(key=random)` 做不到这点，分布会不均
- 第 5 步原地改，所以 `items = random.shuffle(items)` 会得到 None
- 想要「打乱后的副本」用 `random.sample(items, len(items))`，原列表不动
- 元素本身没被复制，列表里是可变对象时还是同一批对象
"""

REWRITES["py.sqlite.connect"] = """
**一句话：** 打开（或新建）一个数据库文件，拿到一张「操作凭证」。

**执行逻辑：**

1. 按路径找这个文件
2. 找到 → 打开；**没找到 → 直接建一个空的**
3. 建立连接对象（后续所有 SQL 都通过它）
4. `.cursor()` 从连接里开一个游标，真正执行 SQL 的是游标
5. 用完 `close()` 关掉

**机器层（可跳过）：** SQLite 没有服务进程，连接就是打开了那个文件并加锁。

**边界（从逻辑推出来）：**

- 第 2 步「没找到就新建」，所以**路径写错不会报错**，你只会得到一个空库
- 写操作要 `commit()` 才落盘，因为默认在事务里
- 多个连接同时写会抢锁，报 `database is locked`
- `":memory:"` 不落地到文件，程序退出就没了，适合测试
"""

