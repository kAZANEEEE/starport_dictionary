REWRITES["py.fs.exists"] = """
**一句话：** 拿着路径去问文件系统一句「这东西在不在」。

**执行逻辑：**

1. 把路径交给操作系统，请它查一下这个位置有没有东西
2. 系统返回「有」或者「没有」；有的话还带一个类型（普通文件 / 目录 / 其它）
3. `exists()` 只看第 2 步有没有东西，不看类型
4. `is_file()` 额外检查类型是不是普通文件，`is_dir()` 检查是不是目录

**机器层（可跳过）：** 一次 `stat` 查询，不读文件内容，只读取元数据。

**边界（从逻辑推出来）：**

- 第 3 步不区分类型，所以**目录也算「存在」**——判断文件必须用 `is_file()`
- 系统说「没有」也可能是路径拼错了、相对路径的基准目录不对，False 不等于「你心里想的那个文件不存在」
- 查得到不等于能读（权限问题在第 3 步之后才暴露）
- 第 2 步是一次真实磁盘查询，放进几万次循环里会明显变慢
"""

REWRITES["py.fs.traverse_directory"] = """
**一句话：** 像翻抽屉——先看这一层有什么，遇到子目录就钻进去继续看。

**执行逻辑：**

1. 列出当前目录下的所有条目
2. 逐个检查：是文件就交给筛选条件判断；是目录就**回到第 1 步**从它里面开始
3. 子目录看完了，退回来继续处理当前目录剩下的条目
4. 全部走完，把符合条件的收集成列表

**机器层（可跳过）：** 每进一层目录就多一次目录读取调用，开销与「目录数 + 文件数」成正比。

**边界（从逻辑推出来）：**

- 第 2 步会钻进子目录，所以结果**包含任意深度的文件**；只要一层就用 `glob("*")`
- 第 1 步会连目录一起返回，所以要 `if p.is_file()` 过滤，否则目录也会被当成结果
- 遇到没权限的子目录，第 1 步直接抛异常，整个遍历中断——需要不想被打断就得在那一步包 `try`
- 数据太多时列表会很大，改成生成器（去掉方括号）就能边遍历边处理
"""

REWRITES["py.os.getcwd"] = """
**一句话：** 问程序一句「你现在站在哪个文件夹里」。

**执行逻辑：**

1. 向操作系统查询当前进程的工作目录
2. 系统把那个目录的绝对路径返回
3. Python 把它包成字符串（`os.getcwd`）或路径对象（`Path.cwd()`）交给你

**机器层（可跳过）：** 这个目录是进程自己记着的一个状态，查询只是把它读出来。

**边界（从逻辑推出来）：**

- 这个目录是**进程级**状态，不是「脚本文件所在的目录」——两者常常不同
- 它会被 `os.chdir()` 改掉，改完之后同一句相对路径就指向别处了
- 双击运行和从命令行运行，起点目录不同，所以相对的 `"data.txt"` 可能指到不同文件
- 要拿脚本自己的目录得用 `Path(__file__).parent`，那和这条不是一回事
"""

REWRITES["py.os.listdir"] = """
**一句话：** 拿到一个目录里所有东西的名字，只给名字、不给路径。

**执行逻辑：**

1. 打开指定目录，读出它里面的目录项
2. 每一项取出名字（不含上级路径）
3. 全部收集成列表返回
4. 只做这一层，**不会钻进子目录**

**机器层（可跳过）：** 一次目录读取，名字直接来自目录表，不需要打开文件。

**边界（从逻辑推出来）：**

- 第 2 步只给名字，所以想拼完整路径得自己 `os.path.join`（或改用 `Path` 的方法）
- 第 4 步不递归，子目录里的东西看不到——要递归用 `walk` 或 `rglob`
- 返回顺序是文件系统给的顺序，**不保证稳定**，要可比就 `sorted()`
- 目录很大时列表会一次性占内存，遍历用 `os.scandir` 更省
"""

REWRITES["py.os.makedirs"] = """
**一句话：** 建目录，中间缺的父目录它也帮你一起建。

**执行逻辑：**

1. 把路径拆成一段段（比如 `a/b/c` → `a`、`b`、`c`）
2. 从最前面开始，逐段检查：这一段存在吗
3. 不存在就建一个；存在就跳过
4. 一直到最末一段建完为止
5. 每一段都是一次独立的建目录动作

**机器层（可跳过）：** 底层是多次 `mkdir` 系统调用，不是一次原子操作。

**边界（从逻辑推出来）：**

- 第 3 步「跳过」是靠 `exist_ok=True` 实现的；不传这个参数，已存在时会抛 `FileExistsError`
- 第 5 步说明它是多步操作，两个进程同时建同一路径可能互相撞，`exist_ok` 能兜住
- 如果中间某段位置上已经是个**文件**，第 3 步之后的建目录必然失败
- 权限不足会停在某一层并抛 `PermissionError`，前面已建的目录会留着
"""

REWRITES["py.os.rename"] = """
**一句话：** 改个名字（或换个所在目录），文件本身一个字节都不动。

**执行逻辑：**

1. 在源目录里找到那个名字对应的条目
2. 检查目标路径的上级目录存在吗、目标名字被占用吗
3. 把目录表里这个条目改指到新的名字/位置
4. 文件内容原地不动，只是登记信息改了

**机器层（可跳过）：** 同盘时只改目录项，属于「改登记」，所以瞬间完成。

**边界（从逻辑推出来）：**

- 第 3 步只在**同一个磁盘分区**内成立；跨盘时那个登记无处可改，抛错——要跨盘必须真的复制一遍（`shutil.move`）
- 第 2 步发现目标名已被占用时，Windows 上会直接报错而不是覆盖；要覆盖得用 `replace`
- 因为不改内容，所以大文件重命名也是瞬间的
- 文件正被别的程序打开时，第 3 步在 Windows 会失败
"""

REWRITES["py.list.find"] = """
**一句话：** 从第一个元素开始挨个对比，找到就停，找完没有就说没有。

**执行逻辑（`in` 与 `index` 其实同一趟）：**

1. 取第 1 个元素，和目标值比较
2. 相等 → 命中：`in` 返回 True；`index` 返回这个位置的下标
3. 不等 → 取下一个，重复第 2 步
4. 全部比完都没命中：`in` 返回 False；`index` 抛 `ValueError`

**机器层（可跳过）：** 逐个比较，O(n)，列表越长越慢。

**边界（从逻辑推出来）：**

- 第 2 步命中即停，所以 `index` 只给**第一次**出现的位置，后面的不管
- 第 4 步 `index` 是抛错而不是返回 -1（那是字符串 `find` 的行为）
- 因为逐项比较，元素多且频繁查就用 `set` / `dict`（查一次一步到位）
- 比较用的是 `==`，所以 `1` 和 `True` 会被认为相等，浮点数比较还会有精度问题
"""

REWRITES["py.list.filter"] = """
**一句话：** 挨个问每个元素「你要不要留下」，要的放进新列表。

**执行逻辑：**

1. 准备一个空的结果列表
2. 取一个元素，交给条件判断
3. 判断为真 → 放进结果；为假 → 丢掉
4. 重复 2–3 直到取完
5. 返回结果列表（`filter` 版本是边问边给，不一次给完）

**机器层（可跳过）：** 一趟遍历，O(n)；条件函数每个元素调用一次。

**边界（从逻辑推出来）：**

- 第 5 步的差别很重要：推导式**立刻建完**整个列表，`filter` 返回的是**迭代器**，不 `list()` 就一次都没算
- 迭代器被消费一次就空了，第二次遍历拿不到东西
- 第 3 步判断的是「真假值」，不是严格布尔：空字符串、0、None 都算假
- 结果永远是**新对象**，原列表不动，元素本身还是同一批引用
"""

REWRITES["py.list.map"] = """
**一句话：** 挨个把元素丢进同一个函数，把每次的返回值收集起来。

**执行逻辑：**

1. 准备一个空的结果列表（推导式）或一个惰性迭代器（`map`）
2. 取一个元素，交给转换函数
3. 拿到返回值，放进结果
4. 重复 2–3 直到取完
5. 交给你结果；元素个数和原来一样

**机器层（可跳过）：** 一趟遍历 + 每元素一次函数调用，O(n)。

**边界（从逻辑推出来）：**

- 第 5 步「个数不变」是它的定义——要减少个数得换成筛选
- `map` 是惰性的：不消费就算一次都没调用，所以调试时打印看不到结果
- 每元素都要调一次函数，函数本身写得很重时会明显变慢，简单运算用推导式内联更快
- 转换函数抛异常会中断整个流程，批量处理时最好在函数里自己兜住
"""

REWRITES["py.list.comprehension"] = """
**一句话：** 它一边造列表一边往里塞，比 `for` 循环少做两件事。

**执行逻辑：**

1. 先造一个空列表（你看不见，但它已经在那儿了）
2. 从来源里取出第一个元素
3. 对它求值，比如算出 `i * 2`
4. 把结果塞进那个列表的末尾
5. 回到第 2 步，直到来源取完
6. 把整个列表交给你

**和 `for` 差在哪：** `for` 在「求值」和「塞进去」之间要多做两步——先找 `append` 在哪、再调用它。推导式把这两步合成固定动作。省的是「元素个数 × 两次小动作」，实测一百万个元素：103 毫秒 → 73 毫秒。

**机器层（可跳过）：** CPython 编成一条专用指令直接追加，不经过函数调用。

**边界（从逻辑推出来）：**

- 第 1 步就建了列表且全程只有一个，所以**元素全部同时待在内存里**，长度=内存占用
- 数据大就改用生成器表达式（圆括号），它不建列表，边算边用
- 加的 `if` 是在第 2 步之后判断的：不合格的元素不进入第 3 步，所以结果个数可能变少
- 别在第 3 步里做副作用（写文件、打印），那会让逻辑难以推断
"""

REWRITES["py.string.join"] = """
**一句话：** 拿着分隔符当「胶水」，把一堆字符串按顺序粘成一条。

**执行逻辑：**

1. 先看要粘的东西有多少个，算出总长度（要留多少位置）
2. 一次性申请好这么大的一块地方
3. 放进第一个字符串
4. 放进胶水（分隔符），再放下一个字符串
5. 重复第 4 步，直到放完
6. 收成一条字符串返回

**机器层（可跳过）：** 因为第 1 步先算总长，全程只分配一次内存。

**边界（从逻辑推出来）：**

- 第 3–5 步依次做，所以胶水**只在元素之间**出现，开头结尾都不会有
- 只接受字符串：列表里有数字会在第 3 步失败（要自己先 `str()`）
- 因为第 1 步要算总长，可迭代对象会被先遍历一次——传生成器也能用，但会被消费
- 循环里用 `+` 拼接等价于每次都重新算长度、重新分配，所以次数多了慢得多
"""

REWRITES["py.string.strip"] = """
**一句话：** 从两头往里剥，剥到遇到「不该剥的字符」就停。

**执行逻辑：**

1. 从左往右看，字符属于「要删的集合」就跳过，遇到第一个不属于的就停
2. 记下这个位置（左边起点）
3. 从右往左做同样的事，遇到第一个不该删的就停
4. 截取这两个位置之间的部分
5. 返回这个新字符串

**机器层（可跳过）：** 两次短距离扫描，只碰两端，开销和字符串长度基本无关。

**边界（从逻辑推出来）：**

- 第 1、3 步都只看两端，所以**中间的空格一个都不会动**
- 传了参数（如 `"xy"`）时，删的是「集合里的任意字符」，不是这个子串——`strip("xy")` 会一路剥掉所有 x 和 y
- 不传参数时集合是「所有空白字符」，包括 `\\t`、`\\n`、`\\r` 和全角空格
- 返回新串、不改原串，所以要重新赋值；只想处理右边用 `rstrip("\\n")`
"""

REWRITES["py.string.startswith"] = """
**一句话：** 拿开头那几个字符和目标比一比，一样就是 True。

**执行逻辑：**

1. 从字符串开头取前 N 个字符（N = 目标的长度）
2. 和目标逐字符比较
3. 全一样 → 返回 True；有一个不一样 → 返回 False
4. 传元组时，对每个候选重复 1–3，任意一个成功即 True
5. `endswith` 完全对称，只是从末尾往前取

**机器层（可跳过）：** 只比较目标长度那么几个字符，和原串多长无关。

**边界（从逻辑推出来）：**

- 第 1 步取的是固定长度，所以原串比目标短时直接 False，不会报错
- 逐字符比较区分大小写：`"Py".startswith("py")` 是 False
- `endswith` 比的是**字符串末尾**，所以带查询串的 URL（`a.py?x=1`）会判错——那要先拆 URL
- 用 `endswith` 判断后缀不安全（`"notpy".endswith("py")` 为真），文件后缀该用 `Path().suffix`
"""

REWRITES["py.string.format"] = """
**一句话：** 先写一条带空位的句子，再把变量的值填进空位。

**执行逻辑：**

1. 扫描模板，找到第一个 `{}` 或 `{名字}`
2. 取出对应的值
3. 按冒号后面的格式规则把它变成文本（比如保留两位小数）
4. 用这段文本替换空位
5. 重复 1–4 直到没有空位
6. 返回拼好的字符串

**机器层（可跳过）：** f-string 在编译期就把「文字」和「表达式」拆开，运行时只做拼接。

**边界（从逻辑推出来）：**

- 第 3 步的格式规则决定小数位、千分位、百分比；不写就按默认字符串形式输出
- 因为空位是按顺序或按名字填的，`.format` 位置传错不会报错，只会填错——f-string 没这个问题
- 想输出真正的花括号要写两层 `{{}}`，否则会被当空位
- 拼 SQL 时值仍然要走参数化，格式化只解决「怎么拼成文本」，不解决安全
"""


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    pattern = re.compile(r"(## 原理解释\n\n)(.*?)(\n## )", re.DOTALL)
    done = 0
    for entry_id, body in REWRITES.items():
        path = ENTRIES / f"{entry_id}.md"
        if not path.is_file():
            print("找不到:", entry_id)
            continue
        text = path.read_text(encoding="utf-8")
        new_text, n = pattern.subn(lambda m: m.group(1) + body.strip() + m.group(3), text, count=1)
        if n != 1:
            print("没匹配到原理解释节:", entry_id)
            continue
        path.write_text(new_text, encoding="utf-8")
        done += 1
    print(f"完成 {done} 条")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
